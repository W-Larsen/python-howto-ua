def mcq(q, options, explain, code=None):
    v = {"q": q}
    if code is not None:
        v["code"] = code
    v["options"] = [{"text": t, "credit": c} for t, c in options]
    v["explain"] = explain
    return v

def prog(title, intro, hint, starter, sample, sampleOut, tests, solution):
    return {"title": title, "intro": intro, "hint": hint, "starter": starter,
            "sample": sample, "sampleOut": sampleOut,
            "tests": [{"input": i, "output": o} for i, o in tests], "solution": solution}

def func(title, fn, sig, intro, hint, starter, tests, solution):
    return {"title": title, "fn": fn, "sig": sig, "intro": intro, "hint": hint, "starter": starter,
            "tests": [{"args": a, "expected": e} for a, e in tests], "solution": solution}

def starter_prog(lines):
    return "\n".join("# " + l if l else "#" for l in lines) + "\n"

