# ============================================================== ГЕНЕРАЦІЯ JS
def js_str(s):
    return json.dumps(s, ensure_ascii=False)

def js_tpl(s):
    return "`" + s.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${") + "`"

def js_val(v):
    return json.dumps(v, ensure_ascii=False, separators=(",", ":"))

def emit_variant(stype, v):
    L = []
    if stype == "mcq":
        L.append(f"    {{ q:{js_str(v['q'])},")
        if "code" in v:
            L.append(f"      code:{js_str(v['code'])},")
        L.append("      options:[")
        L.append(",\n".join(f"        {{ text:{js_str(o['text'])}, credit:{o['credit']} }}" for o in v["options"]))
        L.append("      ],")
        L.append(f"      explain:{js_str(v['explain'])} }}")
    elif stype == "program":
        L.append(f"    {{ title:{js_str(v['title'])},")
        L.append(f"      intro:{js_str(v['intro'])},")
        L.append(f"      hint:{js_str(v['hint'])},")
        L.append(f"      starter:\n{js_tpl(v['starter'])},")
        L.append(f"      sample:{js_str(v['sample'])}, sampleOut:{js_str(v['sampleOut'])},")
        L.append("      tests:[")
        L.append(",\n".join(f"        {{ input:{js_str(t['input'])}, output:{js_str(t['output'])} }}" for t in v["tests"]))
        L.append("      ],")
        L.append(f"      solution:\n{js_tpl(v['solution'])} }}")
    else:
        L.append(f"    {{ title:{js_str(v['title'])}, fn:{js_str(v['fn'])}, sig:{js_str(v['sig'])},")
        L.append(f"      intro:{js_str(v['intro'])},")
        L.append(f"      hint:{js_str(v['hint'])},")
        L.append(f"      starter:\n{js_tpl(v['starter'])},")
        L.append("      tests:[")
        L.append(",\n".join(f"        {{ args:{js_val(t['args'])}, expected:{js_val(t['expected'])} }}" for t in v["tests"]))
        L.append("      ],")
        L.append(f"      solution:\n{js_tpl(v['solution'])} }}")
    return "\n".join(L)

def emit_slots(slots):
    out = []
    for n, s in enumerate(slots, 1):
        out.append(f"  /* ---------- {n}. {s['topic']} — {s['type']} ---------- */")
        out.append(f"  {{ id:{js_str(s['id'])}, type:{js_str(s['type'])}, topic:{js_str(s['topic'])}, points:{s['points']}, variants:[")
        out.append(",\n".join(emit_variant(s["type"], v) for v in s["variants"]))
        out.append("  ]}" + ("," if n < len(slots) else ""))
        out.append("")
    return "\n".join(out)

