def norm(t):
    lines = [l.rstrip() for l in t.replace("\r\n", "\n").split("\n")]
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines)

def run_prog(src, inp):
    feed = iter(inp.split("\n") if inp else [])
    def fake_input(prompt=""):
        return next(feed)
    buf = io.StringIO()
    ns = {"__name__": "__main__", "input": fake_input}
    try:
        with redirect_stdout(buf):
            exec(compile(src, "main.py", "exec"), ns)
        return buf.getvalue(), ""
    except BaseException as e:
        return buf.getvalue(), f"{type(e).__name__}: {e}"

