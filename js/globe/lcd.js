function glyph(ch){
  let code = String(ch).charCodeAt(0);
  if(!(code >= 32 && code <= 126)) code = 63;      /* '?' — як на платі */
  const at = (code - 32) * 5;
  return FONT.slice(at, at + 5);
}

function cssColor(el, name, fallback){
  const v = getComputedStyle(el).getPropertyValue(name).trim();
  return v || fallback;
}

function create(canvas){
  const buf = new Uint8Array(W * H);
  canvas.width = W * S;
  canvas.height = H * S;

  function set(x, y, on){ if(x >= 0 && x < W && y >= 0 && y < H) buf[y * W + x] = on ? 1 : 0; }

  function render(){
    const ctx = canvas.getContext && canvas.getContext("2d");
    if(!ctx) return;
    const bg = cssColor(canvas, "--lcd-bg", "#9fb59a");
    const on = cssColor(canvas, "--lcd-on", "#1d2a1d");
    const ghost = cssColor(canvas, "--lcd-ghost", "rgba(0,0,0,.05)");
    ctx.fillStyle = bg;
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    for(let y = 0; y < H; y++){
      for(let x = 0; x < W; x++){
        ctx.fillStyle = buf[y * W + x] ? on : ghost;
        ctx.fillRect(x * S, y * S, S - 1, S - 1);
      }
    }
  }

  function draw(rows, inv){
    buf.fill(0);
    for(let r = 0; r < ROWS; r++){
      const back = !!(inv && inv[r]);
      const top = r * 8;
      if(back) for(let y = top; y < top + 8; y++) for(let x = 0; x < W; x++) set(x, y, 1);
      const text = String((rows && rows[r]) || "").slice(0, COLS);
      for(let i = 0; i < text.length; i++){
        const g = glyph(text[i]);
        for(let k = 0; k < 5; k++)
          for(let bit = 0; bit < 8; bit++)
            if(g[k] >> bit & 1) set(i * 6 + k, top + bit, !back);
      }
    }
    render();
  }

  function clear(){ buf.fill(0); render(); }

  /* мигання підсвітки: на платі 150 мс без світла і 150 мс зі світлом */
  function blink(times){
    return new Promise((resolve) => {
      let left = Math.max(0, times | 0) * 2;
      const step = () => {
        if(left <= 0){ canvas.classList.remove("off"); resolve(); return; }
        canvas.classList.toggle("off", left % 2 === 0);
        left--;
        setTimeout(step, 150);
      };
      step();
    });
  }

  /* глобус вимкнено: екран тьмяний, доки його знову не ввімкнуть */
  const sleep = (on) => canvas.classList.toggle("sleep", !!on);

  const pixel = (x, y) => buf[y * W + x];

  clear();
  return { draw, clear, blink, sleep, pixel };
}

return { FONT, glyph, create, W, H };
